"""The rsync daemon serving our nodes to paired servers.

Transfers between servers are pulled by the destination's owner (it then
verifies and records the copy itself), so the daemon is **read-only**:
modules are ``read only = yes`` and delete options are refused. Each paired
server has its own user and password; the configuration is rewritten
whenever nodes come and go or pairings change (rsync re-reads it on every
connection), and the daemon only runs while at least one server is paired.
"""

from __future__ import annotations

import logging
import os
import sqlite3
import subprocess
import time
from pathlib import Path

from . import index, peers
from .config import Config
from .transfer import rsync_path

log = logging.getLogger("reifs.rsyncd")


class RsyncDaemon:
    def __init__(self, cfg: Config):
        self.cfg = cfg
        self.dir = Path(cfg.home) / "rsyncd"
        self.conf = self.dir / "rsyncd.conf"
        self.secrets = self.dir / "rsyncd.secrets"
        self.proc: subprocess.Popen | None = None
        self.wanted = False
        self.last_start = 0.0

    def render(self, conn: sqlite3.Connection) -> tuple[str, str, bool]:
        style = self.cfg.rsync.path_style
        users = [(r["rsync_in_user"], r["rsync_in_password"]) for r in peers.paired_peers(conn)
                 if r["rsync_in_user"] and r["rsync_in_password"]]
        lines = [
            "# Generated by rei-fs; do not edit.",
            "use chroot = no",
            "read only = yes",
            "list = no",
            "strict modes = no",
            "refuse options = delete delete-before delete-during delete-delay delete-after"
            " delete-excluded remove-source-files",
            f"secrets file = {rsync_path(self.secrets, style)}",
            f"log file = {rsync_path(self.dir / 'rsyncd.log', style)}",
        ]
        if hasattr(os, "getuid") and os.getuid() == 0:
            # A daemon started by root would switch to "nobody"; keep root's
            # identity so it can read the files. (Setting uid/gid as a normal
            # user fails: rsync then calls setgroups.)
            lines += ["uid = 0", "gid = 0"]
        lines.append("")
        auth = ", ".join(u for u, _ in users)
        for r in conn.execute("SELECT id, name, root_path FROM nodes WHERE owner_id = ?"
                              " AND online = 1 AND root_path IS NOT NULL",
                              (index.self_id(conn),)):
            lines += [f"[{peers.module_name(r['id'])}]",
                      f"    comment = {r['name']}",
                      f"    path = {rsync_path(r['root_path'], style)}",
                      f"    auth users = {auth}",
                      "    exclude = /.rei-fs/",
                      ""]
        secrets_text = "".join(f"{u}:{p}\n" for u, p in users)
        return "\n".join(lines), secrets_text, bool(users)

    def update(self, conn: sqlite3.Connection) -> None:
        """Rewrite the configuration and start/stop the daemon as needed."""
        conf, secrets_text, wanted = self.render(conn)
        self.dir.mkdir(parents=True, exist_ok=True)
        _write(self.secrets, secrets_text, private=True)
        _write(self.conf, conf)
        self.wanted = wanted
        self.ensure()

    def ensure(self) -> None:
        if not self.wanted:
            self.stop()
            return
        if self.proc is not None and self.proc.poll() is None:
            return
        if self.proc is not None and time.monotonic() - self.last_start < 60:
            return  # it just died (port in use?): retry once a minute
        if self.proc is not None:
            log.warning("rsync daemon exited (code %s); restarting", self.proc.returncode)
        self.last_start = time.monotonic()
        host = self.cfg.server.listen.rpartition(":")[0].strip("[]") or "0.0.0.0"
        cmd = [self.cfg.rsync.path, "--daemon", "--no-detach",
               f"--config={rsync_path(self.conf, self.cfg.rsync.path_style)}",
               f"--port={self.cfg.rsync.daemon_port}", f"--address={host}"]
        try:
            self.proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL,
                                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            log.info("rsync daemon started on port %s", self.cfg.rsync.daemon_port)
        except OSError as e:
            self.proc = None
            log.warning("cannot start the rsync daemon (%s): %s", self.cfg.rsync.path, e)

    def stop(self) -> None:
        if self.proc is not None and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        self.proc = None


def _write(path: Path, text: str, private: bool = False) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    if private:
        try:
            os.chmod(tmp, 0o600)
        except OSError:
            pass
    os.replace(tmp, path)
